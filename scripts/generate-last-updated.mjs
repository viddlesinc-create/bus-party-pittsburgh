#!/usr/bin/env node
/**
 * Generates src/lib/last-updated.generated.ts — a route -> ISO-date map used by
 * the visible "Last updated:" line and by dateModified in each page's JSON-LD,
 * so the two can never disagree.
 *
 * The date for a route is the last-commit date of the page component that
 * renders it (plus, for blog posts and location pages, the shared layout they
 * depend on — editing the layout genuinely changes the page).
 *
 * Route -> component is parsed out of src/ssr-routes.tsx rather than duplicated
 * here, so adding a route to the site cannot silently skip this map.
 *
 * Falls back to the build date if git is unavailable (a shallow clone with no
 * history, a tarball export). Never emits a future date.
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(resolve(root, 'src/ssr-routes.tsx'), 'utf8');

// import Fleet from "./pages/Fleet";
const imports = new Map();
for (const m of src.matchAll(/import\s+(\w+)\s+from\s+"\.\/([^"]+)"/g)) {
  imports.set(m[1], `src/${m[2]}.tsx`);
}

// "/fleet": Fleet,
const routes = new Map();
for (const m of src.matchAll(/"([^"]+)":\s*(\w+),/g)) {
  const [, route, comp] = m;
  if (route === '*') continue;
  const file = imports.get(comp);
  if (file) routes.set(route, file);
}

// Layouts whose edits should bump the pages built on them.
const SHARED = {
  '/blog/': 'src/components/BlogPostLayout.tsx',
  '/locations/': 'src/components/LocationPageLayout.tsx',
};

const buildDate = new Date().toISOString().slice(0, 10);
let gitOk = true;

function lastCommit(file) {
  if (!gitOk) return null;
  try {
    const out = execSync(`git log -1 --format=%cI -- "${file}"`, {
      cwd: root, stdio: ['ignore', 'pipe', 'ignore'],
    }).toString().trim();
    return out ? out.slice(0, 10) : null;
  } catch {
    gitOk = false;
    return null;
  }
}

const dates = {};
for (const [route, file] of routes) {
  const candidates = [file];
  for (const [prefix, layout] of Object.entries(SHARED)) {
    if (route.startsWith(prefix) && route !== prefix.slice(0, -1)) candidates.push(layout);
  }
  const found = candidates.map(lastCommit).filter(Boolean).sort();
  // Newest of the page and its layout; build date if git told us nothing.
  let date = found.length ? found[found.length - 1] : buildDate;
  if (date > buildDate) date = buildDate; // never claim a future update
  dates[route] = date;
}

const body = `// GENERATED by scripts/generate-last-updated.mjs — do not edit by hand.
// Regenerated on every build; see the script for how each date is derived.

export const LAST_UPDATED: Record<string, string> = ${JSON.stringify(dates, null, 2)};

/** Build date, used when a route is missing from the map above. */
export const BUILD_DATE = ${JSON.stringify(buildDate)};
`;

writeFileSync(resolve(root, 'src/lib/last-updated.generated.ts'), body);
console.log(
  `last-updated: ${Object.keys(dates).length} routes` +
  (gitOk ? '' : ' (git unavailable — fell back to build date)')
);
